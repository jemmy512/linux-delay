"""Embed the ELF object as C data; does not require a native bpftool/libbpf."""
import argparse
from pathlib import Path
import re


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("object", type=Path)
    parser.add_argument("header", type=Path)
    parser.add_argument("--symbol", default="sched_delay_bpf_bytes")
    args = parser.parse_args()
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", args.symbol):
        parser.error("symbol must be a C identifier")
    data = args.object.read_bytes()
    if len(data) < 20 or data[:6] != b"\x7fELF\x02\x01" or data[18:20] != b"\xf7\x00":
        parser.error("expected a little-endian ELF64 BPF object")
    guard = args.symbol.upper() + "_H"
    lines = [
        "/* Generated by scripts/embed_bpf.py; do not edit. */",
        f"#ifndef {guard}",
        f"#define {guard}",
        f"static const unsigned char {args.symbol}[]",
        "    __attribute__((aligned(8))) = {",
    ]
    for pos in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[pos:pos + 16]) + ",")
    lines.extend(["};", "#endif", ""])
    args.header.parent.mkdir(parents=True, exist_ok=True)
    temporary = args.header.with_suffix(args.header.suffix + ".tmp")
    temporary.write_text("\n".join(lines))
    temporary.replace(args.header)


if __name__ == "__main__":
    main()
